import {readdir,readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const list=[];
async function walk(dir){for(const entry of await readdir(dir,{withFileTypes:true})){const path=dir+'/'+entry.name;if(entry.isDirectory())await walk(path);else if(!['sw.js','.DS_Store'].includes(entry.name))list.push(path.slice(5));}}
await walk('dist');list.sort();
if(list.some(p=>/seed|statement|backup|\.sivault$/i.test(p)))throw Error('Unexpected data file in distributable.');
const hash=createHash('sha256');for(const path of list){hash.update(path);hash.update(await readFile('dist/'+path));}
const version=hash.digest('hex').slice(0,16);
await writeFile('dist/sw.js',`// Generated by scripts/build-offline.mjs. Cache only public application assets.
const CACHE='spend-insights-app-${version}', FILES=${JSON.stringify(list)};
const allowed=new Set(FILES.map(path=>new URL(path,self.registration.scope).href));
self.addEventListener('install',event=>event.waitUntil((async()=>{
 const cache=await caches.open(CACHE);
 try{for(let i=0;i<FILES.length;i+=8)await Promise.all(FILES.slice(i,i+8).map(async path=>{const url=new URL(path,self.registration.scope).href;const response=await fetch(url,{cache:'reload',credentials:'same-origin'});if(!response.ok)throw Error('Asset unavailable');await cache.put(url,response);}));}
 catch(error){await caches.delete(CACHE);throw error;}
 // Updated workers wait for all old tabs to close, avoiding mixed code versions.
})()));
self.addEventListener('activate',event=>event.waitUntil((async()=>{for(const name of await caches.keys())if(name.startsWith('spend-insights-app-')&&name!==CACHE)await caches.delete(name);await self.clients.claim();})()));
self.addEventListener('fetch',event=>{
 const request=event.request,url=new URL(request.url);if(request.method!=='GET'||url.origin!==self.location.origin)return;
 const isHome=request.mode==='navigate'&&url.pathname===new URL(self.registration.scope).pathname&&!url.search;
 const key=isHome?new URL('index.html',self.registration.scope).href:url.href;
 if(!allowed.has(key))return;
 event.respondWith((async()=>{const cache=await caches.open(CACHE);return await cache.match(key)||fetch(request);})());
});
`);
console.log(`Offline asset manifest: ${list.length} files, version ${version}`);
